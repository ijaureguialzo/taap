/// Catálogo de cadenas es/en/eu (equivalente a los String Catalogs;
/// mantiene paridad con los ficheros lang/* del orquestador).
enum LocaleStrings {
    static func t(_ locale: String, _ key: String, vars: [String: String] = [:]) -> String {
        let dict = tables[locale] ?? tables["es"]!
        var s = dict[key] ?? tables["en"]?[key] ?? tables["es"]![key] ?? key
        for (k, v) in vars {
            s = s.replacingOccurrences(of: "%\(k)", with: v)
        }
        return s
    }

    static let supportedLocales = ["es", "en", "eu"]

    static func isSupported(_ locale: String) -> Bool {
        supportedLocales.contains(locale)
    }

    /// Idioma del dispositivo si esta entre los soportados (es/en/eu);
    /// castellano en caso contrario (spec localization).
    static func deviceDefault() -> String {
        let id = Locale.current.identifier.lowercased()
        for locale in supportedLocales where id.hasPrefix(locale) {
            return locale
        }
        return "es"
    }

